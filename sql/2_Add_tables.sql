set search_path = "public";
set time zone 'Europe/Moscow';

CREATE TABLE table_persons
(
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,

    CONSTRAINT ck_table_persons_name_not_blank
        CHECK (btrim(name) <> '')
);

CREATE INDEX ix_table_persons_name
    ON table_persons (name);


CREATE TABLE table_phones
(
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id INTEGER NOT NULL,
    number    TEXT NOT NULL,

    CONSTRAINT ck_table_phones_number_not_blank
        CHECK (btrim(number) <> ''),

    CONSTRAINT fk_table_phones_persons
        FOREIGN KEY (person_id)
        REFERENCES table_persons (id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

CREATE INDEX ix_table_phones_person_id
    ON table_phones (person_id);

--

CREATE VIEW view_phones AS
    SELECT table_phones.id AS id,
           table_persons.name AS name,
           table_phones.number AS number
    FROM table_phones
        JOIN table_persons
            ON table_phones.person_id = table_persons.id;